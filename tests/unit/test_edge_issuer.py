# -- no anchor: today's behaviour, exactly ---------------------------------


def test_no_anchor_reports_the_two_facts_apart_and_changes_nothing(package, tmp_path, owner):
    root, _ = package
    trust = _trust(tmp_path)
    assert trust == NOT_CONFIGURED
    found = inspect(root, trust=trust)
    issuer = found.issuer
    # The headline case: a matching digest and no signature.
    assert issuer.digest_verified is True
    assert issuer.issuer_authenticated is False
    assert issuer.issuer_status == "not_configured"
    assert issuer.issuer_reason == edge_issuer.ISSUER_REASONS["not_configured"]
    assert found.caveats == (UNSIGNED_CAVEAT,)
    assert _evidence(found)["package_present"] is Evidence.PASSED
    assert _evidence(found)["version_matches"] is Evidence.PASSED
    assert _evidence(found)["digest_matches"] is Evidence.PASSED
    event = found.as_event()
    assert event["digest_verified"] is True and event["issuer_authenticated"] is False


