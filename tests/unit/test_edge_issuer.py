"""Edge package issuer authentication, revocation and the rollback floor.

Two facts, never one: `digest_verified` (the artifact re-derives to its
manifest's digest) and `issuer_authenticated` (a detached signature over the
canonical manifest verifies under the configured issuer key). Revocation and
the floor only narrow.

Every key here is generated by the test that uses it, from fresh random
seeds, and signed with the test-only `signing_oracle`. No key, signature or
floor written here is anything but a temporary file under `tmp_path`.
"""

