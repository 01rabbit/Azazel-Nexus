# -- revocation ------------------------------------------------------------


def test_a_revoked_digest_is_refused_although_it_matches(package, tmp_path, seed, owner):
    root, digest = package
    _sign_manifest(root, seed)
    trust = _trust(tmp_path, anchor=_anchor(seed),
                   revocations=_revocations(seed, digests=[digest]))
    found = inspect(root, trust=trust)
    finding = found.finding("digest_matches")
    assert finding.evidence is Evidence.FAILED and finding.security is True
    assert "revoked" in finding.reason
    # The match itself is still reported: the refusal is the revocation's.
    assert found.issuer.digest_verified is True
    assert found.issuer.revoked == "revoked_digest"
    assert found.state().digest_matches is False
    with pytest.raises(EdgePackageRefused):
        installed_package_digest(package_root=root, trust=trust)


