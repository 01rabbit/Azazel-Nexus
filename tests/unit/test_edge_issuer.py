# -- the rollback floor ----------------------------------------------------


def _floor(version: str, digest: str, sequence: int = 0, listed: bytes | None = None) -> bytes:
    """A floor record; `listed` is the signed list whose payload it remembers."""
    payload_digest = ""
    if sequence:
        payload = listed[64:] if listed is not None else b"{}"
        payload_digest = "sha256:" + __import__("hashlib").sha256(payload).hexdigest()
    return encode_floor(EdgeFloor(version=version, package_digest=digest,
                                  revocation_sequence=sequence,
                                  revocation_digest=payload_digest))


def test_a_version_below_the_floor_is_refused(package, tmp_path, owner):
    root, digest = package
    found = inspect(root, trust=_trust(tmp_path, floor=_floor("0.2.0", digest)))
    finding = found.finding("version_matches")
    assert finding.evidence is Evidence.FAILED and finding.security is True
    assert found.issuer.floor_status == "below_floor"
    with pytest.raises(EdgePackageRefused):
        installed_package_digest(package_root=root, trust=_trust(tmp_path))


def test_an_old_signed_manifest_replayed_at_the_floor_version_is_refused(tmp_path, seed, owner):
    # The issuer signed build A of 0.1.0; build B of 0.1.0 was activated and
    # holds the floor. Putting the old, validly signed build A back is a replay.
    old = tmp_path / "old"
    write_package(old, binary=b"\x7fELF build A\n")
    _sign_manifest(old, seed)
    current_digest, _ = write_package(tmp_path / "current", binary=b"\x7fELF build B\n")
    trust = _trust(tmp_path, anchor=_anchor(seed), floor=_floor(PIN.version, current_digest))
    found = inspect(old, trust=trust)
    assert found.issuer.issuer_authenticated is True  # the signature is genuine
