def test_canonical_form_ignores_formatting_and_refuses_ambiguity():
    assert canonical_json(b'{ "b": 1,\n "a": [true, null] }') == b'{"a":[true,null],"b":1}'
    for ambiguous in (b'{"a": 1, "a": 2}', b'{"a": 1.0}', b'{"a": NaN}', b"not json", b""):
        with pytest.raises(IssuerRefused):
            canonical_json(ambiguous)


